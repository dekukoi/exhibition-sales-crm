"""Regenerates evals/handoff_examples.md by actually running the handoff pipeline
against the example briefs — never hand-typed, so the log can't drift from the code
that produces it.

Run from the backend/ directory: `python -m evals.generate_handoff_examples`
"""

from dataclasses import asdict
from decimal import Decimal
from pathlib import Path

from app.handoff import HandoffBrief, HandoffOutcome, run_handoff_pipeline

_BASE = dict(
    opportunity_id=1,
    opportunity_code="OP000001",
    fair_name="Beauty Trade Forum",
    fair_edition_code="BEAUTY-2027",
    max_stand_height_m=Decimal("4.50"),
    description="Next edition: product launch stand",
    brief_notes="Plot confirmed; artwork supplied.",
)

EXAMPLES: list[tuple[str, HandoffBrief]] = [
    (
        "Complete brief",
        HandoffBrief(
            **_BASE,
            client_budget_eur=Decimal("50000.00"),
            stand_area_sqm=Decimal("80.00"),
            requested_height_m=Decimal("4.00"),
        ),
    ),
    (
        "Missing height",
        HandoffBrief(
            **_BASE,
            client_budget_eur=Decimal("50000.00"),
            stand_area_sqm=Decimal("80.00"),
            requested_height_m=None,
        ),
    ),
    (
        "Height over the edition's limit",
        HandoffBrief(
            **_BASE,
            client_budget_eur=Decimal("50000.00"),
            stand_area_sqm=Decimal("80.00"),
            requested_height_m=Decimal("5.00"),
        ),
    ),
    (
        "Heads-up only (fair + budget known, area/height still missing)",
        HandoffBrief(
            **_BASE,
            client_budget_eur=Decimal("50000.00"),
            stand_area_sqm=None,
            requested_height_m=None,
        ),
    ),
]


def _render(title: str, outcome: HandoffOutcome) -> str:
    lines = [f"## {title}", "", "**Brief (input):**", "```json", str(asdict(outcome.brief)), "```", ""]
    lines += [
        "**Preparer** (simulated):",
        f"> {outcome.preparer.proposed_next_step}",
        "",
        "**Checker** (simulated):",
        f"> {outcome.checker.notes}",
        "",
        "**Coordinator** (simulated):",
        f"- verdict: `{outcome.coordinator.verdict}`",
        f"- heads_up: `{outcome.coordinator.heads_up}`",
        f"- reason: {outcome.coordinator.reason}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    sections = [
        "# Handoff-assistant example runs",
        "",
        "Generated by `evals/generate_handoff_examples.py` — every run below is the "
        "actual output of `run_handoff_pipeline`, not hand-typed, so this log can't "
        "drift from the code it documents. All role outputs are the deterministic "
        "local stand-in described in docs/adr/0004 (`simulated: true`), never a real "
        "model call.",
        "",
    ]
    for title, brief in EXAMPLES:
        sections.append(_render(title, run_handoff_pipeline(brief)))

    output_path = Path(__file__).parent / "handoff_examples.md"
    output_path.write_text("\n".join(sections), encoding="utf-8")
    print(f"Wrote {output_path}")


if __name__ == "__main__":
    main()
